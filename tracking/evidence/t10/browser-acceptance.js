async (page) => {
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const errors=[];
  page.on('pageerror', error=>errors.push(error.message));
  await page.reload();
  await page.setViewportSize({width:1280,height:900});
  await page.getByRole('heading',{name:'Study runner',exact:true}).waitFor();
  await page.getByRole('button',{name:'Create synthetic three-arm study'}).click();
  await page.getByRole('button',{name:/^#\d+.*human only.*assigned$/}).waitFor();
  const studyId=await page.getByRole('combobox',{name:'Study',exact:true}).inputValue();
  await page.getByRole('button',{name:/^#\d+.*human only.*assigned$/}).click();
  await page.getByRole('heading',{name:'Human-only workspace'}).waitFor();
  check(await page.getByRole('button',{name:'Execute frozen fixture workflow'}).count()===0,'Human-only work must not offer execution');
  await page.getByLabel('Your document or code').fill('SYNTHETIC automated browser entry: use a shared checklist. This is plumbing evidence, not work from a research participant.');
  await page.getByRole('button',{name:'Save entry',exact:true}).click();
  await page.getByText('Saved verbatim with an immutable content hash.').waitFor();
  await page.getByLabel('Text to check for').fill('checklist');
  await page.getByRole('button',{name:'Run conventional text check'}).click();
  await page.getByText('Text check passed for the saved artifact.').waitFor();
  await page.screenshot({path:'tracking/evidence/t10/human-only-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Submit saved work'}).click();
  await page.getByRole('button',{name:/^#\d+.*human only.*submitted$/}).waitFor();
  await page.getByRole('button',{name:/^#\d+.*autonomous.*assigned$/}).click();
  check(await page.getByRole('button',{name:'Save entry',exact:true}).isDisabled(),'Autonomous artifacts must not accept human help');
  await page.getByRole('button',{name:'Stop attempt'}).click();
  await page.getByRole('button',{name:/^#\d+.*autonomous.*needs_human$/}).click();
  await page.getByRole('button',{name:'Create separate assisted continuation'}).click();
  await page.getByText('assisted continuation, excluded from primary comparison',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Add open-ended fixture baseline'}).click();
  await page.getByRole('button',{name:/^#\d+.*autonomous.*assigned$/}).last().click();
  await page.getByRole('button',{name:'Execute frozen fixture workflow'}).click();
  await page.getByRole('button',{name:/^#\d+.*autonomous.*submitted$/}).waitFor();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export study',exact:true}).click();
  const download=await downloadPromise;
  await download.saveAs('.verification/t10-browser-export.json');
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Phone view must not overflow horizontally');
  await page.screenshot({path:'tracking/evidence/t10/study-mobile.png',fullPage:true});
  check(errors.length===0,`Unexpected page errors: ${errors.join(', ')}`);
  return {passed:true,synthetic:true,study_id:studyId,checks:['three-arm seed','human-only helper absent','verbatim save','bound conventional check','submission','autonomous human-entry disabled','condition-stable needs_human stop','separate continuation','open-ended baseline','export download','390px no horizontal overflow'],page_errors:errors};
}
