import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 1280, height: 1800 } });
const log = [];
page.on('console', (m) => m.type() === 'error' && log.push(`console: ${m.text()}`));
await page.goto('http://127.0.0.1:5173/');
await page.getByRole('heading', { name: /Sign in to review/ }).waitFor();
log.push('signed-out view shows sign-in: ok');
await page.goto('http://127.0.0.1:5173/#login=browser-check-login-code-0123456789ab');
await page.getByRole('heading', { name: 'Decisions, policies and runs' }).waitFor();
log.push(`fragment cleared: ${page.url()}`);
await page.getByText('Decision needed: Allow record.revise').waitFor();
const cards = await page.locator('article.decision').count();
log.push(`pending cards: ${cards}`);
await page.screenshot({ path: `${out}/browser-decisions.png`, fullPage: true });
// Judgment card: options, no approve button.
const judgment = page.locator('article.decision', { hasText: 'JUDGMENT' });
log.push(`judgment has approve button: ${await judgment.getByRole('button', { name: /Approve/ }).count()}`);
log.push(`judgment buttons: ${(await judgment.getByRole('button').allInnerTexts()).join(' | ')}`);
const auth = page.locator('article.decision', { hasText: 'AUTHORIZATION' });
log.push(`approve disabled without reason: ${await auth.getByRole('button', { name: 'Approve this action once' }).isDisabled()}`);
await auth.getByRole('button', { name: /standing policy/ }).click();
log.push(`policy preview: ${(await auth.locator('.policy span').innerText()).trim()}`);
await auth.locator('textarea').fill('Adding owners is routine and reversible.');
await auth.getByRole('button', { name: 'Approve this action once' }).click();
await page.locator('article.decision', { hasText: 'AUTHORIZATION' }).waitFor({ state: 'detached' });
log.push('approve once: card left the pending list');
await page.getByRole('button', { name: 'Show answered and closed' }).click();
await page.getByText(/Answered .*approve once/).waitFor();
log.push('answered view shows approve once with rationale: ok');
await page.screenshot({ path: `${out}/browser-answered.png`, fullPage: true });
await page.setViewportSize({ width: 390, height: 1600 });
await page.screenshot({ path: `${out}/browser-mobile.png`, fullPage: false });
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
log.push(`mobile horizontal overflow: ${overflow}`);
console.log(log.join('\n'));
await browser.close();
