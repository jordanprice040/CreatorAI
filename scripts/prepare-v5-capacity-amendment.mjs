// Preserve original plan/manifests; bind an authorized settings-only amendment.
import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {canonicalHash} from '../packages/domain/dist/index.js';
const dir='tracking/evidence/discovery-qualification-v5/';
const base=JSON.parse(await readFile(dir+'execution-plan.json','utf8'));
const receipt=JSON.parse(await readFile(dir+'cap-increase-receipt.json','utf8'));
assert.equal(canonicalHash(base),'68c59f330da54b3e22933f5e789f520edec3abbcdbf985666ccec5a4f89af37d');
const expected=structuredClone(receipt.before.connection.settings);
expected.caps.shared.max_model_requests_per_day=42;
assert.deepEqual(receipt.after.connection.settings,expected);
let source=await readFile('scripts/qualify-plan-discovery-v5.mjs','utf8');
const start=source.indexOf('const plan = await read(');
const end=source.indexOf('assert.equal(plan.preparation_hash',start);
assert.ok(start>0&&end>start);
source=source.slice(0,start)+`const basePlan = await read('tracking/evidence/discovery-qualification-v5/execution-plan.json');
const addendum = await read('tracking/evidence/discovery-qualification-v5/capacity-authorization.json');
assert.equal(process.argv[4], canonicalHash(addendum), 'Exact owner capacity amendment hash required.');
assert.equal(canonicalHash(basePlan), addendum.original_execution_plan_hash);
assert.equal(createHash('sha256').update(await readFile(new URL(import.meta.url))).digest('hex'), addendum.runner_sha256);
assert.deepEqual(addendum.permitted_delta, {old_daily_cap:40,new_daily_cap:42});
const approvedSettings = await read('tracking/evidence/discovery-qualification-v5/cap-increase-receipt.json');
assert.equal(canonicalHash(approvedSettings.after.connection.settings), addendum.new_settings_hash);
const expectedSettings = structuredClone(approvedSettings.before.connection.settings);
expectedSettings.caps.shared.max_model_requests_per_day=42;
assert.deepEqual(approvedSettings.after.connection.settings, expectedSettings);
assert.equal(approvedSettings.before.connection.settings_hash,basePlan.proposed_settings_hash);
const plan = {...basePlan, proposed_settings_hash:addendum.new_settings_hash};
`+source.slice(end);
source=source.replace('approved_plan_hash: canonicalHash(plan),','approved_plan_hash: canonicalHash(plan),\n    original_execution_plan_hash: canonicalHash(basePlan),\n    capacity_authorization_hash: canonicalHash(addendum),');
await writeFile('scripts/qualify-v5-approved-capacity.mjs',source,{flag:'wx'});
const amendment={format:'v5-owner-capacity-amendment/1',owner_authorization:'I approve you adding more slots to do the testing',original_execution_plan_hash:canonicalHash(base),permitted_delta:{old_daily_cap:40,new_daily_cap:42},new_settings_hash:receipt.after.connection.settings_hash,restore_daily_cap:40,max_new_requests:18,retries:0,timeout_ms:120000,max_wall_ms:2160000,new_metered_spend_nano_usd:'0',credits_unchanged:'confirmed_off',runner_sha256:createHash('sha256').update(source).digest('hex'),note:'Only daily capacity changes. Same installed candidate/frozen cases/scorer/failure stop. Restore40 after bounded attempt; no change to permissions, credits or provider quota.'};
await writeFile(dir+'capacity-authorization.json',JSON.stringify(amendment,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({amendment_hash:canonicalHash(amendment),new_settings_hash:amendment.new_settings_hash,original_plan_unchanged:true}));
